export function normalizarID(texto: string) {
    return texto
        .toLowerCase()
        .replace(/á/g, "a")
        .replace(/é/g, "e")
        .replace(/í/g, "i")
        .replace(/ó/g, "o")
        .replace(/ú/g, "u")
        .replace(/ñ/g, "n")
        .replace(/\s+/g, "-")
        .replace(/[^\w-]+/g, "");
}